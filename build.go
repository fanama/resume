// buildOptions are the renderer options one build needs.
type buildOptions struct {
	docx docx.Options
	pdf  pdf.Options
	adoc adoc.Options
	tex  tex.Options
}

func runBuild(args []string, stdout, stderr io.Writer) error {
	var c commonFlags
	fs := flag.NewFlagSet("build", flag.ContinueOnError)
	c.register(fs)
	if err := c.parse(fs, args, stderr); err != nil {
		return err
	}
	resume, l, err := c.pipeline()
	if err != nil {
		return err
	}
	formats, err := parseFormats(c.format)
	if err != nil {
		return err
	}
	accentHex, accentRGB, err := parseAccent(c.accent)
	if err != nil {
		return err
	}

	dir := c.output
	explicit := dir != "" && hasExt(dir) && len(formats) == 1
	if dir != "" && !explicit {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return fmt.Errorf("create %s: %w", dir, err)
		}
	}
	opts := c.buildOptions(resume, l, accentHex, accentRGB)
	written, rep, err := writeAll(formats, dir, c.baseName(), explicit, l, opts)
	if err != nil {
		return err
	}
	return reportBuild(stdout, stderr, c.quiet, written, rep)
}

// buildOptions assembles the options of every renderer from the flags.
func (c *commonFlags) buildOptions(resume *model.Resume, l *layout.Layout, accentHex string, accentRGB pdf.RGB) buildOptions {
	docxFont := c.font
	if docxFont == "" {
		docxFont = "Calibri"
	}
	header := fmt.Sprintf("Generated by atscv from %s, single column, no table.", filepath.Base(c.input))
	return buildOptions{
		docx: docx.Options{
			FontFamily:   docxFont,
			FontSize:     pick(c.size, 10.5),
			SectionColor: accentHex,
			SectionRules: c.rules,
			LangTag:      langTag(l),
			Author:       resume.Name,
			Title:        resume.Name,
			Keywords:     keywordString(resume),
		},
		pdf: c.pdfOptions(resume, accentRGB),
		adoc: adoc.Options{
			Lang:         l.OptsLang(),
			SectionRules: c.rules,
		},
		tex: tex.Options{
			Lang:         l.OptsLang(),
			SectionRules: c.rules,
			Accent:       accentHex,
			FontSize:     pick(c.size, 10.5),
			Header:       header,
		},
	}
}

// targetPath is where one format is written: an explicit file, a file in the
// output directory, or a file next to the input.
func targetPath(dir, base, format string, explicit bool) string {
	ext := "." + format
	if format == "adoc" {
		ext = ".adoc"
	}
	if explicit {
		return dir
	}
	if dir == "" {
		return base + ext
	}
	return filepath.Join(dir, base+ext)
}

// writeAll renders every requested format and keeps the page report of the PDF.
func writeAll(formats []string, dir, base string, explicit bool, l *layout.Layout, opts buildOptions) ([]string, pdf.Report, error) {
	written := make([]string, 0, len(formats))
	var pdfReport pdf.Report
	for _, format := range formats {
		target := targetPath(dir, base, format, explicit)
		rep, err := writeFormat(format, target, l, opts)
		if err != nil {
			return nil, pdf.Report{}, err
		}
		if format == "pdf" {
			pdfReport = rep
		}
		written = append(written, target)
	}
	return written, pdfReport, nil
}

// writeFormat renders one format to its target. It hands back the page report
// of the PDF, which the render itself measured: the caller needs it for the
// note, and asking for it afterwards would render the document twice.
func writeFormat(format, target string, l *layout.Layout, opts buildOptions) (pdf.Report, error) {
	var err error
	var rep pdf.Report
	switch format {
	case "docx":
		err = writeFile(target, func(w io.Writer) error {
			return docx.Render(w, docx.FromLayout(l), opts.docx)
		})
	case "pdf":
		err = writeFile(target, func(w io.Writer) error {
			var rerr error
			rep, rerr = pdf.RenderReport(w, l, opts.pdf)
			return rerr
		})
	case "adoc":
		err = writeFile(target, func(w io.Writer) error {
			_, werr := io.WriteString(w, adoc.Render(l, opts.adoc))
			return werr
		})
	case "tex":
		err = writeFile(target, func(w io.Writer) error {
			_, werr := io.WriteString(w, tex.Render(l, opts.tex))
			return werr
		})
	case "txt":
		err = writeFile(target, func(w io.Writer) error {
			_, werr := io.WriteString(w, txt.Render(l))
			return werr
		})
	default:
		err = fmt.Errorf("unknown format %q", format)
	}
	if err != nil {
		return pdf.Report{}, fmt.Errorf("%s: %w", format, err)
	}
	return rep, nil
}

func writeFile(path string, fn func(io.Writer) error) error {
	f, err := os.Create(path)
	if err != nil {
		return fmt.Errorf("create %s: %w", path, err)
	}
	if err := fn(f); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}

// reportBuild prints what was written, plus the page note when the PDF spills.
func reportBuild(stdout, stderr io.Writer, quiet bool, written []string, rep pdf.Report) error {
	if quiet {
		return nil
	}
	for _, path := range written {
		fmt.Fprintln(stdout, "wrote", path)
	}
	// The page count comes from the render that just produced the file, and is
	// only said out loud when the document spills: a resume that needs a second
	// page is a content decision, and a silent extra page is how it goes
	// unnoticed. Measuring afterwards would render everything a second time.
	if rep.Pages > 1 {
		fmt.Fprintf(stderr, "note: the PDF runs to %d pages, the last one %.0f%% full; "+
			"the breaks are clean, but fitting on one page means cutting about %.0f mm of content\n",
			rep.Pages, rep.LastPageFill, rep.LastPageFill/100*(297-2*14))
	}
	return nil
}
