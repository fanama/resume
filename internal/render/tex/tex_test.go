func testLayout(lang model.Lang) *layout.Layout {
	r := &model.Resume{
		Lang:     lang,
		Name:     "Jean Dupont",
		Headline: "Développeur Fullstack",
		Contact: model.Contact{
			City: "Paris", Country: "France", Email: "jean@example.com",
			Links: []model.Link{{Label: "GitHub", URL: "https://github.com/fanama"}},
		},
		Summary: "Développeur avec 5 ans d'expérience.",
		Experience: []model.Experience{
			{
				Title: "Développeur", Company: "SFR", Location: "Paris",
				Start: "2023-01", End: "present",
				Highlights: []string{"Plateforme LLM pour 1000 utilisateurs par jour"},
				Stack:      []string{"React", "NodeJS"},
			},
			{
				Title: "Stagiaire", Company: "Acme", Location: "Lyon",
				Start: "2021", End: "2021",
			},
		},
		Education: []model.Education{
			{Degree: "Master", School: "SU", Start: "2016", End: "2018"},
		},
		Skills: []model.SkillGroup{{Category: "Backend", Items: []string{"Go", "SQL"}}},
	}
	return layout.New(r, layout.Options{Lang: lang})
}

func TestRender(t *testing.T) {
	out := Render(testLayout(model.LangFR), Options{
		Lang: model.LangFR, SectionRules: true,
		Header: "Generated by atscv from resume.fr.json",
	})
	if !strings.HasPrefix(out, "% Generated by atscv from resume.fr.json\n") {
		t.Errorf("the header comment is missing:\n%s", firstLines(out, 3))
	}
	for _, want := range []string{
		`\documentclass[10pt,a4paper]{article}`,
		`\usepackage[a4paper,margin=14mm]{geometry}`,
		`\usepackage[french]{babel}`,
		`\definecolor{accent}{HTML}{1F3864}`,
		`\pagestyle{empty}`,
		`PROFIL`,
		`EXPÉRIENCE PROFESSIONNELLE`,
		`{\color{accent}\bfseries Technologies:} React, NodeJS`,
		`\begin{itemize}`,
		`\item Plateforme LLM pour 1000 utilisateurs par jour`,
		`github.com/fanama`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in:\n%s", want, out)
		}
	}
	// The name is the first block of the document, and it is not repeated:
	// a parser reads it once, at the top, like in the other renderers.
	if strings.Count(out, "Jean Dupont") != 1 {
		t.Errorf("the name appears %d times, want once:\n%s",
			strings.Count(out, "Jean Dupont"), out)
	}
}

// TestNoTableNoImageNoBox is the LaTeX side of the ATS contract: a table, a
// minipage or an image turns the resume into a reading order nobody can
// guess, and a page style would print a number a parser picks up as content.
func TestNoTableNoImageNoBox(t *testing.T) {
	out := Render(testLayout(model.LangFR), Options{Lang: model.LangFR, SectionRules: true})
	for _, unwanted := range []string{
		`\begin{table}`, `\begin{tabular}`, `minipage`, `parbox`,
		`\includegraphics`, `tikz`, `tcolorbox`, `hyperref`, `\href`, `\url`,
		`\begin{frame}`, `\section{`, `\tableofcontents`, `\footnote`,
		`\pagestyle{plain}`, `\markboth`, `\pagestyle{fancy}`,
	} {
		if strings.Contains(out, unwanted) {
			t.Errorf("the LaTeX holds %q, which breaks the reading order", unwanted)
		}
	}
	// Achievement lines are list items, not a typed dash.
	for _, line := range strings.Split(out, "\n") {
		if strings.HasPrefix(line, "- ") {
			t.Errorf("a typed dash was found, use a list item: %q", line)
		}
	}
	if !strings.Contains(out, `\end{itemize}`) {
		t.Error("the list of achievements is never closed")
	}
}

// TestEscapesEverySpecialCharacter guards the compile: a resume is user
// text, and a single "&" or "\" written as-is makes pdflatex fail on a file
// the tool claims to have produced.
func TestEscapesEverySpecialCharacter(t *testing.T) {
	r := &model.Resume{
		Name:    `Rakoto & fils_50% #1`,
		Contact: model.Contact{City: `A {ville}`},
		Summary: `Coût $5 ~ ^ \done`,
	}
	out := Render(layout.New(r, layout.Options{Lang: model.LangFR}), Options{Lang: model.LangFR})
	for _, want := range []string{
		`Rakoto \& fils\_50\% \#1`,
		`A \{ville\}`,
		`Coût \$5 \textasciitilde{} \textasciicircum{} \textbackslash{}done`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing the escaped form %q in:\n%s", want, out)
		}
	}
	// A raw special character never survives outside a comment line.
	for _, line := range strings.Split(out, "\n") {
		if strings.HasPrefix(line, "%") {
			continue
		}
		for _, r := range strings.ReplaceAll(line, `\&`, "") {
			if r == '&' {
				t.Errorf("a raw & reached the source: %q", line)
			}
		}
	}
}

// TestTheScaleIsOne pins the typographic scale to the pdf: the body is the
// reference, the name is +4.5, the headings +1, the dates -1 and the contacts
// -1.5, and every leading follows its size.
func TestTheScaleIsOne(t *testing.T) {
	out := Render(testLayout(model.LangFR), Options{Lang: model.LangFR})
	for _, want := range []string{
		`\fontsize{15}{18.75}\selectfont`,    // name, 10.5 + 4.5
		`\fontsize{11.5}{14.375}\selectfont`, // headline and headings, +1
		`\fontsize{9.5}{11.875}\selectfont`,  // date lines, -1
		`\fontsize{9}{11.25}\selectfont`,     // contacts, -1.5
		`\fontsize{10.5}{13.125}\selectfont`, // body
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q, the scale drifted from the pdf:\n%s", want, out)
		}
	}
	// -size moves the whole scale, not just the body.
	big := Render(testLayout(model.LangFR), Options{Lang: model.LangFR, FontSize: 12})
	if !strings.Contains(big, `\fontsize{16.5}{20.625}\selectfont`) {
		t.Errorf("a body of 12 pt did not move the name to 16.5:\n%s", big)
	}
}

// TestSectionRules keeps the hairlines under the option: they are part of
// the design, but a document that asks for none must not draw one.
func TestSectionRules(t *testing.T) {
	plain := Render(testLayout(model.LangFR), Options{Lang: model.LangFR})
	if strings.Contains(plain, `\rule{`) {
		t.Error("a rule was drawn without the option:\n" + plain)
	}
	ruled := Render(testLayout(model.LangFR), Options{Lang: model.LangFR, SectionRules: true})
	// One under every heading, plus the one under the identity block.
	if n := strings.Count(ruled, `\rule{`); n < 3 {
		t.Errorf("%d rules drawn, want one per section plus the identity one:\n%s", n, ruled)
	}
}

// TestHeadingKeepsItsFirstLine is the LaTeX side of the pagination rule: a
// heading, its rule and the first line it announces move together, so a page
// never starts with a word that means nothing alone.
func TestHeadingKeepsItsFirstLine(t *testing.T) {
	for _, rules := range []bool{false, true} {
		out := Render(testLayout(model.LangFR), Options{Lang: model.LangFR, SectionRules: rules})
		if !strings.Contains(out, `PROFIL\par}`+"\n"+`\nopagebreak[4]`) {
			t.Errorf("rules=%v: the heading is not tied to what follows:\n%s", rules, out)
		}
		if !strings.Contains(out, `\interlinepenalty=10000 \bfseries\color{accent}`) {
			t.Errorf("rules=%v: the heading paragraph can be split:\n%s", rules, out)
		}
	}
}

// TestTheSpacerIsABreakpoint keeps the gap between two entries open: a page
// must be allowed to fall between two entries, never inside one.
func TestTheSpacerIsABreakpoint(t *testing.T) {
	out := Render(testLayout(model.LangFR), Options{Lang: model.LangFR})
	if !strings.Contains(out, `\vspace{3mm}`) {
		t.Error("two entries are not separated by the rhythm of the pdf:\n" + out)
	}
	// The title and its date line are tied together instead.
	if !strings.Contains(out, "SFR, Paris | 01/2023 - Aujourd'hui\\par}"+"\n"+`\nopagebreak[4]`) {
		t.Errorf("a title can leave its dates on another page:\n%s", out)
	}
}

func TestEnglishLayout(t *testing.T) {
	out := Render(testLayout(model.LangEN), Options{Lang: model.LangEN})
	if !strings.Contains(out, `\usepackage[english]{babel}`) {
		t.Error("the english babel option is missing")
	}
	if strings.Contains(out, `\usepackage[french]{babel}`) {
		t.Error("the french babel option leaked into the english document")
	}
	if !strings.Contains(out, `PROFESSIONAL EXPERIENCE`) {
		t.Errorf("the english heading is missing:\n%s", out)
	}
	if strings.Contains(out, `EXPÉRIENCE`) {
		t.Error("a french heading leaked into the english document")
	}
}

func TestAccentIsTheOneOfTheDocument(t *testing.T) {
	out := Render(testLayout(model.LangFR), Options{Lang: model.LangFR, Accent: "0A3B2C"})
	if !strings.Contains(out, `\definecolor{accent}{HTML}{0A3B2C}`) {
		t.Errorf("the accent did not reach the file:\n%s", out)
	}
	// A value that is not a color never reaches the file, where it would
	// fail the compile instead of the request.
	bad := Render(testLayout(model.LangFR), Options{Lang: model.LangFR, Accent: "rebeccapurple"})
	if !strings.Contains(bad, `\definecolor{accent}{HTML}{1F3864}`) {
		t.Errorf("a malformed accent was not replaced by the default:\n%s", bad)
	}
	if strings.Contains(bad, "rebeccapurple") {
		t.Error("a malformed accent reached the source")
	}
}

func TestHeaderComment(t *testing.T) {
	out := Render(testLayout(model.LangFR), Options{
		Lang: model.LangFR, Header: "line one\nline two",
	})
	if !strings.HasPrefix(out, "% line one\n% line two\n") {
		t.Errorf("the header comment is wrong:\n%s", firstLines(out, 3))
	}
}

func TestEmptyLayoutStillCompiles(t *testing.T) {
	l := layout.New(&model.Resume{}, layout.Options{Lang: model.LangFR})
	out := Render(l, Options{})
	for _, want := range []string{`\documentclass`, `\begin{document}`, `\end{document}`} {
		if !strings.Contains(out, want) {
			t.Errorf("an empty resume still needs a whole document, missing %q:\n%s", want, out)
		}
	}
	if strings.Count(out, `\begin{itemize}`) != strings.Count(out, `\end{itemize}`) {
		t.Errorf("a list is left open:\n%s", out)
	}
}

func firstLines(s string, n int) string {
	lines := strings.SplitN(s, "\n", n+1)
	if len(lines) > n {
		lines = lines[:n]
	}
	return strings.Join(lines, "\n")
}
